document.addEventListener('DOMContentLoaded', () => {
  initBlog();
});

function initBlog() {
  const blogGrid = document.getElementById('blog-posts-grid');
  const searchInput = document.getElementById('blog-search-input');
  const filterBtns = document.querySelectorAll('.filter-btn');
  
  // Modal Elements
  const modal = document.getElementById('article-reader-modal');
  const modalClose = document.getElementById('close-modal-btn');
  const modalTag = document.getElementById('modal-article-tag');
  const modalTitle = document.getElementById('modal-article-title');
  const modalMeta = document.getElementById('modal-article-meta');
  const modalText = document.getElementById('modal-article-text');

  let currentCategory = 'all';
  let searchQuery = '';

  // Render initial posts
  renderPosts();

  // Category Filtering
  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      currentCategory = btn.getAttribute('data-category');
      renderPosts();
    });
  });

  // Search Input Filtering
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      searchQuery = e.target.value.toLowerCase().trim();
      renderPosts();
    });
  }

  // Render function
  function renderPosts() {
    if (!blogGrid) return;
    
    // Filter logic
    const filtered = BLOG_POSTS.filter(post => {
      const matchesCategory = currentCategory === 'all' || post.category.toLowerCase() === currentCategory.toLowerCase();
      const matchesSearch = post.title.toLowerCase().includes(searchQuery) || 
                            post.summary.toLowerCase().includes(searchQuery) ||
                            post.content.toLowerCase().includes(searchQuery);
      return matchesCategory && matchesSearch;
    });

    // Clear grid
    blogGrid.innerHTML = '';

    if (filtered.length === 0) {
      blogGrid.innerHTML = `
        <div style="grid-column: 1 / -1; text-align: center; padding: 4rem 1rem;">
          <p style="font-size: 1.2rem; font-style: italic; color: var(--color-text-muted);">No articles found matching your criteria. Try adjusting your search.</p>
        </div>
      `;
      return;
    }

    // Render cards
    filtered.forEach(post => {
      const card = document.createElement('div');
      card.className = 'blog-card reveal active'; // active immediately for search updates
      
      card.innerHTML = `
        <div class="blog-card-img" style="background-image: linear-gradient(135deg, var(--color-primary-light), var(--color-primary)); opacity: 0.85; display: flex; align-items: center; justify-content: center;">
          <span style="font-family: var(--font-serif); font-size: 2.5rem; font-weight: bold; color: var(--color-white); opacity: 0.85;">${post.category}</span>
        </div>
        <div class="blog-card-content">
          <span class="blog-tag">${post.category}</span>
          <h3>${post.title}</h3>
          <p>${post.summary}</p>
          <div class="blog-card-meta">
            <span>${post.date} &bull; ${post.readTime}</span>
          </div>
        </div>
      `;

      card.addEventListener('click', () => {
        openArticleModal(post);
      });

      blogGrid.appendChild(card);
    });
  }

  // Modal Open
  function openArticleModal(post) {
    if (!modal) return;
    
    modalTag.textContent = post.category;
    modalTitle.textContent = post.title;
    modalMeta.textContent = `${post.date} | ${post.readTime} | Written by Vanessa, LCSW`;
    modalText.innerHTML = post.content;
    
    modal.classList.add('active');
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden'; // Stop background scrolling
  }

  // Modal Close
  function closeArticleModal() {
    if (!modal) return;
    modal.classList.remove('active');
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = ''; // Resume background scrolling
  }

  if (modalClose) {
    modalClose.addEventListener('click', closeArticleModal);
  }

  // Close modal clicking overlay
  if (modal) {
    modal.addEventListener('click', (e) => {
      if (e.target === modal) {
        closeArticleModal();
      }
    });
  }

  // Escape key closure
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('active')) {
      closeArticleModal();
    }
  });
}
